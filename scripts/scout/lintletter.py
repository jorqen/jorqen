"""Проверка сопроводительного письма по формальной части канона.

Зачем скриптом, а не глазами. Канон в `letter-guide.md` держит два рода правил:
суждение («один конкретный факт про их продукт») и механику («длинного тире быть
не должно»). Механику модель проверяет плохо — ровно потому, что сама её и
нарушает: маркеры генератора незаметны тому, кто их производит. Список
конечный, проверка объективная, значит это работа алгоритма.

Что НЕ проверяется и проверяться не должно: релевантность кейса, честность
утверждений, тон. Это суждение, оно остаётся модели и человеку.
"""

from __future__ import annotations

import re
import sys

# ──────────────────────────────────────────────────────────────────────────────
# Правила. Каждое — (код, регулярка, что не так, как чинить)
# ──────────────────────────────────────────────────────────────────────────────

# Тире помечается ВСЁ, без попытки отличить грамматическое от риторического.
#
# Первая версия пробовала различать: разрешала тире между двумя именными
# группами (замена пропущенной связки, «Go — основной язык»). На живом примере
# выяснилось, что эвристика пропускает почти всё — «Senior Go Developer — я не
# просто разработчик» по форме неотличимо от связки. Линтер, который молчит про
# главный маркер, хуже отсутствующего: правило про тире и есть причина, по
# которой его завели.
#
# Поэтому решение обратное: помечаем каждое тире и говорим, какое единственное
# оправдано. Ложная тревога здесь стоит одного взгляда, пропуск — письма,
# которое читается как сгенерированное.
_DASH_ANY = re.compile(r"—|–|--")

_RU_WORDS = (
    "ключев", "комплексн", "синерги", "являюсь", "осуществля", "данный ",
    "в рамках", "играет важную роль", "немаловажно", "стоит отметить",
    "зарекомендовал", "широкий спектр", "глубокая экспертиза",
    "прошу рассмотреть", "доброго времени суток", "уважаемый работодатель",
    "командный игрок", "быстро обучаюсь", "стрессоустойчив",
)
_EN_WORDS = (
    "delve", "leverage", "robust", "seamless", "landscape", "realm", "tapestry",
    "underscore", "pivotal", "meticulous", "testament", "foster", "harness",
    "elevate", "spearhead", "cutting-edge", "streamline", "holistic",
    "passionate about", "excited about the opportunity", "proven track record",
    "dear sir", "to whom it may concern", "align with your needs",
    "i am writing to express", "detail-oriented", "i am excited to apply",
)
_PHRASES = (
    ("не просто", "«не просто X, а Y» — самый частый оборот генератора"),
    ("not just", "«not just X, but Y» — самый частый оборот генератора"),
    ("это не про", "«это не про X, это про Y» — оборот генератора"),
    ("в современном мире", "штамп-открывашка"),
    ("в эпоху", "штамп-открывашка"),
    ("как опытный", "начало «Как опытный…» читается как шаблон"),
    ("as a passionate", "начало «As a passionate…» читается как шаблон"),
    ("буду рад возможности обсудить", "шаблонный финал"),
    ("would welcome the opportunity", "шаблонный финал"),
    ("i believe my skills", "шаблонный финал"),
)


def _lines(text: str) -> list[str]:
    return text.splitlines()


def check(text: str) -> list[tuple[str, str, str]]:
    """[(код, что не так, как чинить)]. Пусто — формальная часть канона соблюдена."""
    out: list[tuple[str, str, str]] = []
    low = text.lower()

    # ── тире ──────────────────────────────────────────────────────────────────
    for i, line in enumerate(_lines(text), 1):
        for m in _DASH_ANY.finditer(line):
            fragment = line[max(0, m.start() - 30):m.end() + 30]
            out.append(("dash", f"строка {i}: тире в «…{fragment.strip()}…»",
                        "перепиши двумя предложениями или через запятую. "
                        "Единственное оправданное тире — вместо пропущенной связки "
                        "по-русски («Go — основной язык команды»); в английском "
                        "письме тире не нужно вовсе"))

    # ── слова-метки ───────────────────────────────────────────────────────────
    for w in _RU_WORDS + _EN_WORDS:
        if w in low:
            out.append(("word", f"слово-метка: «{w.strip()}»",
                        "замени конкретикой или выкинь: это слово встречается "
                        "в каждом втором сгенерированном письме"))

    # ── обороты ───────────────────────────────────────────────────────────────
    for needle, why in _PHRASES:
        if needle in low:
            out.append(("phrase", f"оборот «{needle}»: {why}", "перепиши"))

    # ── форма ─────────────────────────────────────────────────────────────────
    if re.search(r"^\s*[-*•]\s+", text, re.M):
        out.append(("format", "список в письме",
                    "письмо идёт сплошным текстом: списки и markdown в почте "
                    "и мессенджере разъезжаются"))
    if re.search(r"\*\*|^#{1,6}\s", text, re.M):
        out.append(("format", "markdown в письме", "убери разметку"))
    if re.search(r"[\U0001F300-\U0001FAFF☀-➿]", text):
        out.append(("format", "эмодзи в письме", "убери"))
    if text.count(";") > 1:
        out.append(("style", "точки с запятой больше одной",
                    "для короткого письма это тяжело; но это правило КРАТКОСТИ, "
                    "а не признак генератора — люди ставят её чаще моделей, "
                    "и вычищать пунктуацию ради «человечности» вредно"))

    # ── длинные предложения на союзе ──────────────────────────────────────────
    # Замер 07.08.2026: тире перестало быть надёжной приметой генератора, а
    # ВМЕСТО него ею стала нехватка пунктуации — модели сцепляют длинные
    # предложения союзом «и»/and, он у них самое частое слово.
    for sent in re.split(r"(?<=[.!?])\s+", text):
        n = len(re.findall(r"\S+", sent))
        joins = len(re.findall(r"\b(?:и|and)\b", sent, re.I))
        if n > 40 and joins >= 2:
            out.append(("run-on", f"предложение на {n} слов с {joins} союзами: "
                                  f"«{sent[:60].strip()}…»",
                        "разбей: длинная фраза, собранная на «и», — примета "
                        "генератора вместо длинного тире"))
            break

    # ── длина ─────────────────────────────────────────────────────────────────
    words = len(re.findall(r"\S+", text))
    if words > 400:
        out.append(("length", f"{words} слов — длиннее 400",
                    "режь: даже в Европе, где письмо ждут целиком, 400 это потолок"))
    elif words < 60:
        out.append(("length", f"{words} слов — короче 60",
                    "проверь, что есть позиция, кейс с цифрой и ссылка"))

    # ── переносы внутри абзаца ────────────────────────────────────────────────
    # Требование владельца от 25.07.2026: абзац — одна строка любой длины.
    # Мягкая эвристика: короткая строка, за которой сразу идёт непустая, — это
    # почти наверняка ручной перенос, а не конец абзаца.
    lines = _lines(text)
    for i in range(len(lines) - 1):
        cur, nxt = lines[i].rstrip(), lines[i + 1].strip()
        if cur and nxt and len(cur) < 90 and not cur.endswith((".", "!", "?", ":")):
            out.append(("wrap", f"строка {i + 1}: перенос внутри абзаца",
                        "абзац — ОДНА строка любой длины; при копировании в форму "
                        "жёсткие переносы рвут текст посреди фразы"))
            break
    return out


def report(text: str, *, where: str = "письмо") -> int:
    """Печатает находки. Код возврата: 0 — чисто, 1 — есть что чинить."""
    found = check(text)
    # Счёт слов ОТДЕЛЬНОЙ строкой, а не внутри f-строки: там экранирование
    # обратного слэша съедало регулярку, и письмо на двести слов рапортовало
    # «0 слов» — число, которое выглядит фактом и им не является.
    words = len(re.findall(r"\S+", text))
    if not found:
        print(f"{where}: формальная часть канона соблюдена ({words} слов)")
        return 0
    print(f"{where}: {len(found)} замечаний")
    for code, what, how in found:
        print(f"  [{code}] {what}\n        → {how}")
    print("\nСуждение это НЕ проверяет: релевантность кейса, честность "
          "утверждений и тон остаются на тебе (letter-guide.md).")
    return 1


def cli(args) -> int:
    path = getattr(args, "file", None)
    if path and path != "-":
        with open(path, encoding="utf-8") as f:
            return report(f.read(), where=path)
    return report(sys.stdin.read(), where="stdin")
