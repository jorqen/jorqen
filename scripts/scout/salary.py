# И главное: на русском тексте price-parser выдаёт ЛОЖНУЮ валюту — в «Зарплатная
# вилка: 1900-3100 USD на руки» он видит валюту «р» (буква из слова «Зарплата»)
# и теряет USD; таких строк в корпусе восемь. Поменять свой разбор на такой —
# значит поменять один класс молчаливых ошибок на другой, того же сорта.
#
# ЧТО ВСЁ-ТАКИ ВЗЯТО ГОТОВОГО. price-parser подключён последним ходом ТОЛЬКО для
# валюты и только там, где наша таблица не узнала ничего: у него 208 кодов ISO
# против наших семи десятков, и поддерживает их он, а не мы. Импорт ленивый и в
# try/except ImportError: пакета нет — разбор продолжает работать целиком нашим
# кодом. Облачная рутина не имеет права умереть из-за отсутствующего пакета.
#
# Корпус — часть контракта: test_scout.test_salary_corpus гоняет все 498 строк и
# печатает каждое расхождение. Любая правка здесь проверяется им, а не глазами.
#
# ЧТО РАЗБОР ОТКАЗЫВАЕТСЯ ДЕЛАТЬ, И ЭТО НЕ ПРОБЕЛ, А РЕШЕНИЕ. Правка 06.08.2026
# закрыла пять дыр (день и неделя, неоднозначные знаки валют, две вилки в одной
# строке, опечатки площадок, справочные вилки), и у каждой общий знаменатель:
# молчание дешевле уверенной ошибки. Поэтому здесь никогда не появится
# «валюта по умолчанию», «месяц по умолчанию» и «наверное, тут потерян ноль».
# Всё, что разбор увидел, но не положил в вилку, он проговаривает в salary_note,
# и адаптеры кладут это в raw — человеку, а не в колонку денег.

# Невидимые символы, которыми площадки и телеграм-каналы «украшают» текст:
# нулевой ширины пробел/несоединитель/соединитель и BOM. Глазами их нет,
# для регулярки они буквы. Живой пример: getmatch-бот пишет «₽/‍мес» с U+200D
# между слэшем и «мес» — шаблон `/\s*мес` по нему не срабатывал, и вилка
# 400 000 ₽/мес приезжала БЕЗ периода, то есть неотличимо от годовой.
_ZERO_WIDTH = re.compile(r"[​-‍⁠﻿]")

# Число вместе с разделителями разрядов: пробелами (в том числе неразрывными),
# точками, запятыми и апострофом («CHF 120'000»).
_NUM = r"\d[\d\s   .,'’]*"

# Коды валют словом. Регистр не важен: площадки пишут и «EUR», и «eur».
_CUR_CODES = (
    "RUB RUR USD EUR GBP KZT BYN BYR UAH AMD AZN KGS MDL TJS TMT UZS "
    "PLN CZK HUF BGN RSD HRK ISK SEK NOK DKK ILS CHF AED SAR QAR KWD BHD OMR "
    "JOD EGP MAD TND NGN ZAR KES GHS INR PKR BDT LKR NPR CNY JPY KRW HKD TWD "
    "SGD MYR THB IDR VND CAD AUD NZD MXN BRL ARS CLP COP"
).split()

# Эти коды — ещё и обычные слова («try», «gel», «ron»), поэтому ищутся только
# заглавными. PHP (филиппинское песо) не ищется вовсе: в вакансиях это язык, а
# не деньги, и «PHP developer, 5000» превратилось бы в филиппинскую зарплату.
_CUR_CODES_UPPER = ("TRY", "GEL", "RON")

# Маркер валюты → ISO. Список плоский, а выбирается из него САМЫЙ ЛЕВЫЙ маркер
# строки — не первый по порядку таблицы. Это разбор живых потерь: в «100 000 £/€»
# площадка называет фунт первым, а перебор по словарю отдавал евро; в
# «$181,000 - $226,000 / year (£110,416 - £138,020 / year)» ведущая валюта —
# доллар, а фунт стоит в скобках справочно.
#
# Доллары с приставкой стоят выше голого «$» и найдутся раньше него по позиции:
# «CA$ 120 000» до 05.08.2026 опознавался как USD, то есть канадская вилка ехала
# в отчёт завышенной примерно на треть и выглядела при этом совершенно нормально.
_CUR_MARKS: tuple[tuple[str, str | None], ...] = (
    (r"US\$", "USD"), (r"CA\$|C\$", "CAD"), (r"AU\$|A\$", "AUD"),
    (r"NZ\$", "NZD"), (r"HK\$", "HKD"), (r"SG\$|S\$", "SGD"),
    (r"NT\$", "TWD"), (r"MX\$", "MXN"), (r"R\$", "BRL"),
    # Рубль: знак, слово и «2000р/час». Голая «р» — ТОЛЬКО сразу после числа,
    # иначе «ср. рын. зп 300 000 ₽» и «после вычета» делают строку рублёвой
    # по первой попавшейся букве.
    (r"₽|руб\w*|рубл\w*|(?<=\d)\s?р\b\.?", "RUB"),
    (r"₸|тңг|теңге|тенге", "KZT"),
    (r"₾|лари", "GEL"), (r"֏|драм\w*", "AMD"), (r"₴|грн|гривн\w*", "UAH"),
    (r"₺|лир[аы]", "TRY"), (r"₹", "INR"), (r"฿", "THB"), (r"₪", "ILS"),
    (r"₩", "KRW"), (r"₦", "NGN"), (r"₫", "VND"), (r"₱", "PHP"),
    # 円 — японский иероглиф, других валют не носит.
    (r"円", "JPY"),
    # ── знаки, которые носит СРАЗУ НЕСКОЛЬКО валют ─────────────────────────────
    # Код с ведущим «?» — не валюта, а вопрос: разрешает его _resolve_ambiguous
    # по контексту строки. Не нашлось контекста — валюта остаётся неизвестной.
    # Именно так и надо: выдуманная валюта хуже отсутствующей, потому что
    # печатается тем же уверенным тоном, что и настоящая, и в отчёте
    # «45 000 kr» как SEK против NOK — это разница в 5 % , а «¥5 000 000»
    # как JPY против CNY — разница в двадцать раз.
    #
    # Rp — единственный в этой группе, у кого ответ один: индонезийская рупия.
    # Он стоит здесь, а не выше, только чтобы «Rp» разбирался раньше голого «R».
    (r"(?<![A-Za-z])Rp\.?(?![A-Za-z])", "IDR"),
    (r"(?<![A-Za-z])kr\.?(?![A-Za-z])", "?kr"),
    # ZAR пишут «R1 000 000». Голая R перед числом — самый опасный знак из всех:
    # в живой выдаче она почти всегда НЕ деньги, а номер («Job Number: R0242440»,
    # «UNECE R155»). Поэтому здесь только заглавная R вплотную к числу, а
    # южноафриканской она становится лишь при южноафриканском же контексте.
    (r"(?<![A-Za-z0-9])(?-i:R)(?=\s?\d)", "?R"),
    (r"¥|￥", "?¥"),
    (r"zł|злот\w*", "PLN"), (r"Kč", "CZK"), (r"soʻm|сум\w*", "UZS"),
    # Границы буквенные, а не `\b`: «1200PLN/day» и «110 000$» пишут без пробела,
    # и `\bPLN\b` такой код не видел вовсе — валюту вытаскивал price-parser, то
    # есть НЕОБЯЗАТЕЛЬНАЯ зависимость. Разбор без неё обязан работать так же.
    (rf"(?<![A-Za-z])(?:{'|'.join(_CUR_CODES)})(?![A-Za-z])", None),
    (rf"(?<![A-Za-z])(?-i:{'|'.join(_CUR_CODES_UPPER)})(?![A-Za-z])", None),
    (r"\$", "USD"), (r"€", "EUR"), (r"£", "GBP"),
)

# Одна таблица — один источник правды. Прежние `_CUR_SIGN` (словарь знаков) и
# `_CUR_BEFORE` (валюта перед числом) убраны намеренно: они дублировали те же
# данные, и правка валюты «не в том словаре» осталась бы без всякого эффекта —
# ровно так «тңг» и жил в одном списке, но не в другом.
_CUR_ANY = "(?:" + "|".join(p for p, _ in _CUR_MARKS) + ")"
_CUR_RE = re.compile(
    "|".join(f"(?P<c{i}>{p})" for i, (p, _) in enumerate(_CUR_MARKS)), re.I)

# Чем разрешается неоднозначный знак: страна, город, язык, соседний код ISO.
# Проверяется ВСЯ строка целиком, а не окрестность знака: у EURES страна стоит
# в начале («Location: Oslo, Norway … 785000 kr»), у телеграм-каналов — в конце.
#
# Список намеренно короткий: это не географический справочник, а разбор того,
# что реально пишут в вакансиях. Не хватило контекста — валюта не угадывается.
_CUR_AMBIGUOUS: dict[str, tuple[tuple[str, str], ...]] = {
    "?kr": (
        (r"\bSEK\b|\bskr\b|швец|swed|sverige|stockholm|стокгольм|göteborg|malmö", "SEK"),
        (r"\bNOK\b|\bnkr\b|норвеж|норвег|norway|norge|norsk|oslo|осло|bergen|trondheim", "NOK"),
        (r"\bDKK\b|\bdkr\b|дани|датск|denmark|danmark|dansk|copenhagen|københavn|"
         r"копенгаген|aarhus|odense", "DKK"),
        (r"\bISK\b|исланд|iceland|ísland|reykjav|рейкьявик", "ISK"),
    ),
    "?R": (
        (r"\bZAR\b|south\s+afric|южн\w*\s+африк|\bюар\b|johannesburg|йоханнесбург|"
         r"cape\s+town|кейптаун|pretoria|претори|durban|дурбан|sandton", "ZAR"),
    ),
    "?¥": (
        # Иероглифы — самый надёжный признак: «600万円」 не бывает китайским.
        (r"\bJPY\b|япон|japan|nippon|tokyo|токио|osaka|осака|kyoto|円|万円|日本", "JPY"),
        (r"\bCNY\b|\bRMB\b|кита|china|chinese|beijing|пекин|shanghai|шанха|"
         r"shenzhen|guangzhou|元|人民币", "CNY"),
    ),
}


def _resolve_ambiguous(sentinel: str, t: str) -> str | None:
    """Неоднозначный знак → код ISO по контексту строки. Контекста нет — None.

    None здесь не «не смогли», а сознательный ответ: вилка без валюты честно
    выглядит сомнительной, вилка с выдуманной валютой — совершенно нормальной.
    """
    for pattern, code in _CUR_AMBIGUOUS.get(sentinel, ()):
        if re.search(pattern, t, re.I):
            return code
    return None


def _currency(t: str) -> str | None:
    """Валюта строки: самый левый маркер. Ничего не нашлось — None.

    Наш перебор идёт первым, а не библиотечный, потому что он знает русские
    формы («руб», «тенге», «2000р/час») и не принимает букву из слова «Зарплата»
    за валюту — а price-parser принимает.

    Неоднозначный знак (`kr`, `R`, `¥`) разрешается контекстом строки. Если
    контекста нет, возвращается None — и НЕ делается попытки взять следующий
    маркер справа: правило «валюта строки — самая левая» держится именно на том,
    что ведущая валюта настоящая, а всё правее неё — справочный пересчёт.
    """
    m = _CUR_RE.search(t)
    if m:
        for i, (_, code) in enumerate(_CUR_MARKS):
            got = m.group(f"c{i}")
            if got is None:
                continue
            if code and code.startswith("?"):
                return _resolve_ambiguous(code, t)
            return code or got.strip().upper()
    return _currency_fallback(t)


# Коды, которые библиотека возвращать не должна ни при каких обстоятельствах:
# в тексте вакансии это слова, а не деньги. «PHP developer, 5000» price-parser
# читает как пять тысяч филиппинских песо — проверено, именно так и читает.
# TRY/GEL/RON наша таблица берёт только заглавными; воскрешать их со строчных
# через библиотеку значит обойти собственную же осторожность.
_CUR_TRAPS = frozenset({"PHP", "ALL", "TRY", "GEL", "RON"})


def _currency_fallback(t: str) -> str | None:
    """Последний ход — price-parser, и только за кодом ISO, которого нет у нас.

    Зачем вообще библиотека, если разбор свой: у неё 208 кодов ISO и ~170 знаков,
    и обновляет их она. Наша таблица покрывает то, что реально приезжает с наших
    площадок; исландская крона или чилийское песо в ней появятся ровно тогда,
    когда кто-нибудь заметит пропажу в отчёте — то есть поздно.

    Жёстко ограничено тремя буквами A–Z: на русском тексте price-parser выдаёт
    ложную валюту «р» (буква из слова «Зарплата»), и пускать его сырой ответ
    в поле «валюта» нельзя. Импорт ленивый и необязательный: пакета нет —
    строка просто останется без валюты, а не уронит прогон.
    """
    try:
        from price_parser import Price  # noqa: PLC0415 — зависимость необязательная
    except ImportError:
        return None
    try:
        raw = (Price.fromstring(t).currency or "").strip().upper()
    except Exception:  # noqa: BLE001 — чужой код в горячем пути разбора
        return None
    if len(raw) != 3 or not (raw.isascii() and raw.isalpha()) or raw in _CUR_TRAPS:
        return None
    return raw


# Дробная ставка: «$26.08/hr». Хвост из ОДНОЙ-ДВУХ цифр после точки или запятой —
# это копейки, и только у почасовой ставки: в месячных и годовых вилках их не пишет
# никто, а «€2.500 / месяц» и «19.800K – 24.000 PLN» — это разряды, не копейки.
# Без этого правила ставка 26,08 $/час печаталась бы как 2608 $/час — ровно та
# ошибка, которую в freehire чинили отдельной правкой промпта («$26.08/hr → 26,
# never 2608»). У нас таких строк в базе пока нет; правило поставлено заранее,
# потому что цена ошибки — стократное завышение в колонке «деньги».
_DECIMAL_RATE = re.compile(r"^\s*(\d{1,4})[.,](\d{1,2})\s*$")
_HOURLY_RE = re.compile(r"в час|за час|почасов|per\s*hour|/\s*(?:hr|hour|h)\b|hourly|/\s*час",
                        re.I)


def _num(s: str, hourly: bool = False) -> int | None:
    """Число из куска строки: цифры подряд, разделители разрядов выброшены.

    Разделитель разрядов не угадывается: «12.000,00» в вакансиях не встречается,
    а «19.800K – 24.000 PLN» и «€2.500 / месяц» — встречаются, и там точка именно
    разрядная. Копейки в вилках не пишет никто — кроме почасовых ставок, и для
    них есть `hourly`.
    """
    if hourly:
        m = _DECIMAL_RATE.match(s or "")
        if m:
            return int(round(float(f"{m.group(1)}.{m.group(2)}")))
    s = re.sub(r"[^\d]", "", s or "")
    return int(s) if s else None


# Суммы через K пишут geekjob, hirehi и Glassdoor: «от 350K ₽», «EUR 90K - EUR 130K».
# Без разворота множителя разбор отдавал 350 рублей вместо 350 000 — не падение,
# а уверенно напечатанная ложь в колонке «деньги», ошибка ровно в тысячу раз.
#
# Границы жёсткие с обеих сторон: слева не буква (иначе «OK» станет числом),
# справа не буква и не цифра (иначе «K8s» и «100Kb» превратятся в вилку).
_K_SUFFIX = re.compile(r"(?<![\w])(\d+(?:[.,]\d+)?)\s*(?:[KkКк]|тыс\.?)(?![\w])")

# Миллионы и миллиарды — та же ошибка, только в тысячу раз дороже. «от 3 млн руб»
# разбиралось в 3: вакансия с зарплатой три миллиона вставала в отчёте последней
# строкой как «3 ₽», то есть выглядела худшим предложением из всех. Найдено
# 05.08.2026 при сверке с грамматикой денег из natasha/yargy.
#
# Порядок применения важен: сначала млрд, потом млн, потом тысячи, иначе «1,5 млрд»
# после разворота тысяч превратится в мусор.
_M_SUFFIX = re.compile(r"(?<![\w])(\d+(?:[.,]\d+)?)\s*(?:млн\.?|миллион\w*|mln|M)(?![\w])")
_B_SUFFIX = re.compile(r"(?<![\w])(\d+(?:[.,]\d+)?)\s*(?:млрд\.?|миллиард\w*|bln)(?![\w])")

# Множитель, названный ОДИН РАЗ на всю вилку: «$48–90k / year», «400-450K ₽»,
# «от 250 до 350 тыс руб», «30-45k THB», «2-3K$». Нижняя граница остаётся без
# суффикса, и посуффиксный разворот делал из вилки «48–90 000»: нижняя граница
# в тысячу раз меньше верхней. В отчёте это выглядело как вакансия «от 48 $».
#
# Разворачивается ТОЛЬКО справа налево: множитель в конце вилки относится к обеим
# границам, а вот «19.800K – 24.000 PLN» (слева K, справа нет) — это уже две
# самостоятельные суммы, и трогать правую нельзя.
# «M» только заглавной — ровно как в _M_SUFFIX: со строчной «m» под re.I в вилку
# полезли бы метры и минуты.
_MULT_WORD = r"[KkКк]|тыс\.?|млн\.?|миллион\w*|mln|(?-i:M)|млрд\.?|миллиард\w*|bln"
_RANGE_MULT = re.compile(
    rf"(?<![\w.,])(\d+(?:[.,]\d+)?)\s*([—–\-−]|\bдо\b|\bto\b)\s*"
    rf"({_CUR_ANY})?\s*(\d+(?:[.,]\d+)?)\s*({_MULT_WORD})(?![\w])", re.I)


def _mult_factor(word: str) -> int:
    w = (word or "").lower().rstrip(".")
    if w.startswith(("млрд", "миллиард", "bln")):
        return 1_000_000_000
    # «m» сюда попадает только от заглавной M (шаблон уважает регистр), и это
    # миллион: «$1-2M» — это миллионы, а не тысячи.
    if w.startswith(("млн", "миллион", "mln")) or w == "m":
        return 1_000_000
    return 1000


def expand_k(text: str | None) -> str | None:
    """«350K» → «350000», «1,5K» → «1500», «3 млн» → «3000000», «48–90k» → «48000–90000».

    Множители разворачиваются от большего к меньшему: разверни сначала тысячи,
    и «1,5 млрд» останется с недоразобранным хвостом. Вилка с одним множителем
    на две границы разворачивается ПЕРВОЙ — иначе нижняя граница остаётся
    в тысячу раз меньше верхней.
    """
    if not text:
        return text

    def mul(factor: int):
        def repl(m: re.Match) -> str:
            return str(int(round(float(m.group(1).replace(",", ".")) * factor)))
        return repl

    def pair(m: re.Match) -> str:
        factor = _mult_factor(m.group(5))
        lo = int(round(float(m.group(1).replace(",", ".")) * factor))
        hi = int(round(float(m.group(4).replace(",", ".")) * factor))
        return f"{lo} {m.group(2)} {m.group(3) or ''}{hi}"

    text = _RANGE_MULT.sub(pair, text)
    text = _B_SUFFIX.sub(mul(1_000_000_000), text)
    text = _M_SUFFIX.sub(mul(1_000_000), text)
    return _K_SUFFIX.sub(mul(1000), text)


# Граница вилки: тире любого начертания, «до», «to», «..». Валюта и мусор вокруг
# разделителя («4000$-6000$», «от 3 000 $ до 5 000 $», «до ~$2,5k») пропускаются
# отдельным классом: без этого вилка молча превращалась в «от нижней границы»,
# то есть верхние условия исчезали, а строка выглядела законной.
_SEP = r"(?:[—–‒―\-−]|\.\.\.?|\bдо\b|\bto\b)"
# Точка в списке мусора — не мелочь: «от 150 тыс. руб. до 170 тыс. руб.» без неё
# обрывалось на нижней границе, потому что между числом и «до» стояло «руб.».
_GAP = rf"(?:[\s~≈≥>+.]|{_CUR_ANY}){{0,4}}"
# «от 3 до 5 лет опыта» — не вилка. Требование опыта стоит в тех же строках, что
# и деньги, и до 05.08.2026 разбиралось в зарплату «от 3 до 5».
_NOT_MONEY_AFTER = r"(?!\s*(?:лет|года|years?|yrs?)\b)"
_RANGE_RE = re.compile(rf"({_NUM}){_GAP}{_SEP}{_GAP}({_NUM}){_NOT_MONEY_AFTER}", re.I)
_FROM_RE = re.compile(rf"\b(?:от|from|starting\s+from)\b{_GAP}({_NUM})", re.I)
_TO_RE = re.compile(rf"(?:\bдо\b|\bup\s+to\b){_GAP}({_NUM})", re.I)

# gross/net словами всех площадок сразу. «до налогов», «гросс», «brutto» и
# «before taxes» — живые формы из телеграм-каналов, и без них вилка приезжала
# «периода нет, вычетов нет», то есть до вычета и на руки стояли в отчёте
# неразличимо. Разница между ними — 13 %, и она решает, стоит ли откликаться.
_GROSS_RE = re.compile(r"\bgross\b|\bbrutto\b|гросс|брутто|до вычет\w*|до налог\w*|"
                       r"before\s+tax\w*", re.I)
_NET_RE = re.compile(r"\bnet\b|\bnetto\b|нетто|на руки|после вычет\w*|после налог\w*|"
                     r"after\s+tax\w*|чистыми", re.I)

_NO_SALARY_RE = re.compile(r"з/п не указана|не указан|зарплата не указана", re.I)

# Ниже этого порога число без валюты — не деньги, а год публикации, номер или
# срок опыта. С валютой порог не нужен: «$400» и «1.5K ₽» написаны как деньги.
_JUNK_BELOW = 10000

# ──────────────────────────────────────────────────────────────────────────────
# Справочная вилка вместо предложения работодателя
# ──────────────────────────────────────────────────────────────────────────────
#
# «По итогам собеседования (ср. рын. зп 300 000 ₽ – 370 000 ₽)» — это НЕ вилка
# вакансии. Работодатель здесь как раз ОТКАЗАЛСЯ называть деньги, а числа взяты
# из чужого обзора рынка. До 06.08.2026 такие строки приезжали в отчёт обычной
# вилкой: 300–370 тысяч выглядели предложением, которого никто не делал, — и по
# ним же считался «средний чек» выдачи.
#
# Выбрасывается не строка целиком, а КЛАУЗА со справкой: скобка, если оборот
# внутри скобок, иначе — от оборота до «;», перевода строки или конца. Поэтому
# «от 350 000 ₽ (ср. рын. 300 000 – 370 000)» сохраняет настоящую вилку и теряет
# только справку, а не обе сразу.
_REF_RE = re.compile(
    r"ср\.?\s*рын\w*|среднерыночн\w*|средн\w*\s+(?:зп|з/п|зарплат\w*)|"
    r"в\s+среднем\s+по\s+рынку|по\s+рынку\s*:?\s*(?:зп|з/п|зарплат\w*)|"
    r"for\s+reference|reference\s+(?:range|salary)|market\s+(?:average|median)",
    re.I)


def _clause_bounds(t: str, start: int, end: int) -> tuple[int, int]:
    """Границы куска, который уходит вместе со справочным оборотом.

    Скобка предпочтительнее «до конца строки»: справку почти всегда пишут именно
    в скобках, и обрезать по ней — значит не задеть то, что стоит после.
    """
    par = t.rfind("(", 0, start)
    close = t.find(")", par) if par != -1 else -1
    if par != -1 and close >= end:
        return par, close + 1
    stop = [p for p in (t.find(";", end), t.find("\n", end)) if p != -1]
    return start, min(stop) if stop else len(t)


def _cut_reference(t: str) -> tuple[str, str | None]:
    """Убирает справочные вилки. Возвращает (остаток строки, что убрано)."""
    cut = []
    # Больше трёх справочных оборотов в одной строке не бывает; ограничение —
    # чтобы кривой шаблон не смог зациклить разбор на живом прогоне.
    for _ in range(3):
        m = _REF_RE.search(t)
        if not m:
            break
        lo, hi = _clause_bounds(t, m.start(), m.end())
        cut.append(t[lo:hi].strip(" ()"))
        t = f"{t[:lo]} {t[hi:]}"
    return t, "; ".join(x for x in cut if x) or None


