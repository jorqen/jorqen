def parse_salary(text: str | None) -> tuple[int | None, int | None, str | None, bool | None]:
    """Разбирает «от 250 000 до 400 000 ₽», «400 000 ₽», «$3000–5000», «2 800—12 500 USD».

    Возвращает (от, до, валюта, gross) — четвёрку, которую ждут полтора десятка
    адаптеров. Период отдаёт period_from_text, а всё, что разбор увидел, но
    сознательно НЕ положил в вилку (вторая вилка строки, справочная вилка,
    невероятная граница), — salary_note. Три функции вместо одной именно затем,
    чтобы контракт из четырёх значений не пришлось ломать.
    """
    return _analyze(text)[:4]


def period_from_text(text: str | None) -> str | None:
    """Период из текста вилки. Ничего не нашлось — None, и это честнее догадки.

    У habr, hh-текстов и ATS-досок период живёт (если живёт) прямо в строке денег.
    Нет слова — значит площадка периода не назвала: подставлять «месяц» по умолчанию
    нельзя, именно так почасовые ставки и превращаются в «зарплату».
    """
    return _analyze(text)[4]


# Потолок правдоподобной МЕСЯЧНОЙ выплаты по валютам. Выше него число месячным
# быть не может — значит период годовой, как его ни называй.
_MONTHLY_CEILING = {"USD": 30_000, "EUR": 30_000, "GBP": 25_000, "CHF": 30_000,
                    "PLN": 100_000, "RUB": 1_500_000, "KZT": 15_000_000}


def period_by_magnitude(lo: int | None, hi: int | None,
                        currency: str | None) -> str | None:
    """«Год» по ВЕЛИЧИНЕ, когда площадка периода не назвала. Иначе None.

    Догадка ровно одна и в одну сторону: число, слишком большое для месяца,
    месячным не бывает. Обратное («слишком маленькое — значит час») не делается
    вовсе: маленькая вилка бывает и настоящей, а ошибка там дороже.

    🔴 Живой счёт 09.08.2026: jooble отдаёт американские вилки без периода
    («197 300–225 100 USD»), и в шорт-листе они печатались рядом с «от 240 000
    RUB/мес». Сравнивать это человеку невозможно: разница в двенадцать раз
    выглядит как разница в двенадцать раз, только в другую сторону.
    """
    cap = _MONTHLY_CEILING.get((currency or "").upper())
    if not cap:
        return None
    top = max(x for x in (lo, hi, 0) if x is not None)
    return "year" if top > cap else None


def salary_note(text: str | None) -> str | None:
    """Что разбор увидел в строке, но НЕ положил в поля вилки. Нечего сказать — None.

    Место этому в `raw` вакансии, а не в колонке денег: человек, открывший
    карточку, должен увидеть «в строке ещё одна вилка: 116-142 PLN/hour» или
    «верхняя граница ниже нижней — вилка не отдана» и решить сам. Молчание здесь
    было бы худшим вариантом: строка выглядела бы разобранной начисто.
    """
    return _analyze(text)[5]
