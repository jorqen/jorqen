# Потолок правдоподобия в долларах на период. Числа намеренно завышены в разы
# против всего, что реально встречается: задача — отсечь опечатку на три-шесть
# порядков, а не спорить с редкой, но настоящей вилкой топ-консультанта. Именно
# поэтому «493–5588 EUR per hour» из EURES проходит: $5588 в час — чушь, но чушь
# ВОЗМОЖНАЯ, а выбрасывать по подозрению мы не имеем права.
_SANE_USD = {"hour": 10_000, "day": 20_000, "week": 100_000,
             "month": 300_000, "year": 3_000_000, None: 3_000_000}


def _implausible(value: int, currency: str | None, period: str | None) -> bool:
    """Столько за такой период не платит никто ни в одной валюте."""
    rate = _PER_USD.get((currency or "").upper(), _UNKNOWN_PER_USD)
    return value / rate > _SANE_USD.get(period, _SANE_USD[None])


def _money(n: int | None) -> str:
    return "?" if n is None else f"{n:,}".replace(",", " ")


def _analyze(text: str | None) -> tuple[int | None, int | None, str | None,
                                        bool | None, str | None, str | None]:
    """Полный разбор строки денег: (от, до, валюта, gross, период, примечание).

    Наружу выходит тремя функциями — parse_salary, period_from_text и
    salary_note, — но считается за один проход, потому что решения зависят друг
    от друга: правдоподобие суммы проверяется ОТНОСИТЕЛЬНО периода, период
    относится к ОСНОВНОЙ вилке, а основная вилка — это то, что осталось после
    выброса справочной.

    Суффикс тысяч и миллионов разворачивается ДО разбора: «350K ₽» — это 350 000,
    «от 3 млн руб» — три миллиона. Площадки, которые так пишут, в реестре есть
    (geekjob, hirehi, Glassdoor, телеграм-каналы), и раньше каждая из них молча
    теряла три нуля.
    """
    if not text:
        return None, None, None, None, None, None
    t = _ZERO_WIDTH.sub("", H.unescape(str(text)))
    t, ref = _cut_reference(t)
    t = expand_k(t.replace(" ", " ").replace(" ", " ").replace(" ", " ")).strip()
    notes = []
    if ref:
        notes.append(f"справочная вилка, а не предложение работодателя: «{ref}»")
    if not t or _NO_SALARY_RE.search(t):
        return None, None, None, None, None, _join(notes)

    cur = _currency(t)
    gross = True if _GROSS_RE.search(t) else (False if _NET_RE.search(t) else None)
    # Копейки бывают только у почасовой ставки — см. _DECIMAL_RATE.
    hourly = bool(_HOURLY_RE.search(t))
    period = _period_of(t)

    # ВТОРАЯ ВИЛКА В СТРОКЕ. «UoP: 16000-20000 PLN gross; B2B: 116-142 PLN/hour» —
    # это два разных предложения одной вакансии, а не вилка от 116 до 20 000.
    # В поля идёт ПЕРВАЯ: её называют основной формой занятости, и именно её
    # площадки кладут в свои же структурированные поля. Вторая уходит в
    # примечание — потому что публичный контракт parse_salary это четвёрка
    # (от, до, валюта, gross), его ждут полтора десятка адаптеров, и ломать его
    # ради строки, которая встречается дважды на пятьсот, нельзя. Примечание
    # адаптеры кладут в raw: там оно видно человеку и не притворяется вилкой.
    ranges = list(_RANGE_RE.finditer(t))
    if len(ranges) > 1:
        notes.append(f"в строке ещё одна вилка: «{t[ranges[1].start():][:60].strip()}»")

    def keep(lo: int | None, hi: int | None):
        # Числа без валюты и мельче порога — мусор строки, а не условия работы.
        biggest = max([x for x in (lo, hi) if x is not None], default=None)
        if biggest is None or (cur is None and biggest < _JUNK_BELOW):
            return None, None, cur, gross, period, _join(notes)
        # Опечатка площадки: «€43,000 – €53,75» (потерянный ноль). Верх ниже низа
        # физически невозможен, и чинить его догадкой нельзя — 53,75 могло быть
        # и 53 750, и 537 500. Отдаём одну границу, факт — в примечание.
        if lo is not None and hi is not None and hi < lo:
            notes.append(f"верхняя граница ниже нижней ({_money(lo)} – {_money(hi)}), "
                         f"похоже на опечатку площадки — вилка не отдана")
            hi = None
        if lo is not None and _implausible(lo, cur, period):
            notes.append(f"нижняя граница {_money(lo)} {cur or ''}"
                         f"{PERIOD_SUFFIX.get(period or '', '')} неправдоподобна — "
                         f"не отдана")
            lo = None
        if hi is not None and _implausible(hi, cur, period):
            notes.append(f"верхняя граница {_money(hi)} {cur or ''}"
                         f"{PERIOD_SUFFIX.get(period or '', '')} неправдоподобна — "
                         f"не отдана")
            hi = None
        return lo, hi, cur, gross, period, _join(notes)

    rng = ranges[0] if ranges else None
    if rng:
        return keep(_num(rng.group(1), hourly), _num(rng.group(2), hourly))
    only_from = _FROM_RE.search(t)
    if only_from:
        return keep(_num(only_from.group(1), hourly), None)
    only_to = _TO_RE.search(t)
    if only_to:
        return keep(None, _num(only_to.group(1), hourly))
    single = _first_number(t, cur)
    if single:
        return keep(_num(single.group(1), hourly), None)
    return None, None, cur, gross, period, _join(notes)


def _join(notes: list[str]) -> str | None:
    return "; ".join(notes) or None


_NUM_ONLY_RE = re.compile(rf"({_NUM})")
_CUR_MARK_RE = re.compile(rf"(?:{_CUR_ANY})", re.I)


def _first_number(t: str, cur: str | None) -> re.Match | None:
    """Первое ЧИСЛО строки — не цифра из слова и не хвост идентификатора.

    Это последняя ветка разбора, куда попадают строки без вилки и без «от/до»,
    и до 06.08.2026 она брала первое попавшееся вхождение цифр. Живые потери:
    «phase2: … $150/week» разбиралось в «2 USD», а «Job Number: R0242440DevOps
    Platform Engineer» — в вилку на 242 440 из ниоткуда.

    Исключение одно: число вплотную к знаку валюты («€2.500», «R900 000»), и то
    лишь когда валюта строки в итоге ОПОЗНАНА. У «R0242440» она не опознана ровно
    потому, что южноафриканского контекста в строке нет, — и это то самое место,
    где осторожность с неоднозначным знаком окупается второй раз.
    """
    for m in _NUM_ONLY_RE.finditer(t):
        head = t[:m.start()]
        if not head or not head[-1].isalnum():
            return m
        if cur and any(x.end() == m.start() for x in _CUR_MARK_RE.finditer(t)):
            return m
    return None


# ──────────────────────────────────────────────────────────────────────────────
# Период
# ──────────────────────────────────────────────────────────────────────────────
#
# Период, названный прямо в строке вилки: «300 000 ₽ в месяц», «$60 per hour».
#
# Русские формы через слэш («/мес», «/ год», «₽/час») тут отдельной веткой,
# и это разбор живой потери: шаблоны требовали ЛИБО предлога («в месяц»), либо
# английского слова, и «81 000 EUR / год», «150 000 ₽/мес», «5 500 USD / месяц»
# не матчились НИ ОДНИМ. Период молча оставался неизвестным, а вилка печаталась
# без суффикса — то есть годовая и месячная стояли в таблице неразличимо.
# Так пишут и телеграм-каналы, и getmatch, и habr.
#
# День и неделя добавлены 06.08.2026 вместе с model.PERIOD_SUFFIX. Раньше здесь
# стояло «показать без суффикса честнее, чем выдать за месячную» — это было
# верно ровно до тех пор, пока показывать было нечем. Живых дневных строк в базе
# три десятка («1000 EUR per day», «900-1200 PLN per day»), недельных четыре
# («$150/week»), и без периода дневная ставка 1000 EUR читалась как позорная
# месячная вилка — то есть вакансию отбрасывали, не глядя.
#
# У дня и недели, в отличие от часа/месяца/года, слово периода принимается ТОЛЬКО
# вплотную к деньгам (_NEAR_MONEY): в вакансиях «день» и «неделя» гораздо чаще
# означают график, а не оплату. Без этой привязки заголовок hnhiring «Hybrid
# (Belgium, 3 days/week) … Visa + €10k» становился недельной вилкой, а строка
# «объём работы — до 20 000 знаков в сутки» — дневной.
#
# «Не дальше чем через несколько символов» — это цифра или знак валюты, потом
# необязательный код валюты, приклеенный к числу без пробела («1200PLN/day»),
# потом до трёх небуквенных символов. Код требует НЕ МЕНЬШЕ двух букв нарочно:
# с одной буквой сюда пролезало «40h/week» — а это график, а не оплата.
_NEAR_MONEY = rf"(?:\d|{_CUR_ANY})(?:[A-Za-z]{{2,4}})?[^\w]{{0,3}}"

_PERIOD_TEXT = (
    ("hour", r"в час|за час|почасов|per\s*hour|/\s*(?:hr|hour|h)\b|hourly|/\s*час"),
    ("day", rf"{_NEAR_MONEY}(?:в день|за день|в сутки|за смену|per\s*day|/\s*day|"
            rf"/\s*дн\w*|daily|day\s*rate)"),
    ("week", rf"{_NEAR_MONEY}(?:в недел\w*|за недел\w*|per\s*week|/\s*week|"
             rf"/\s*нед\w*|weekly|week\s*rate)"),
    ("month", r"в месяц|за месяц|per\s*month|/\s*mo(?:nth)?\b|monthly|at\s+month|"
              r"/\s*мес(?:яц)?\w*"),
    ("year", r"в год|за год|годов\w*|per\s*year|per\s*annum|/\s*(?:yr|year)|yearly|annual|"
             r"/\s*год\w*"),
)

_NUM_RE = re.compile(_NUM)


def _period_scope(t: str) -> str:
    """Кусок строки, в котором период относится к ОСНОВНОЙ вилке.

    «ЗП: $90 000 – $120 000 в год / $7500 – $10800 месяц» называет два периода
    сразу, и поиск по всей строке отдавал тот, что попался первым по таблице.
    Для основной вилки верен только тот период, что стоит ДО следующей суммы:
    всё, что после неё, относится уже к другому предложению. Так «16000-20000 PLN
    gross; B2B: 116-142 PLN/hour» перестало быть почасовым.
    """
    rng = _RANGE_RE.search(t)
    if not rng:
        return t
    nxt = _NUM_RE.search(t, rng.end())
    return t[:nxt.start()] if nxt else t


def _period_of(t: str) -> str | None:
    scope = _period_scope(t)
    for period, pattern in _PERIOD_TEXT:
        if re.search(pattern, scope, re.I):
            return period
    return None


