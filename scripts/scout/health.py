"""health — не деградировал ли источник по сравнению с прошлыми прогонами.

Зачем модуль существует. Покрытие честно внутри ОДНОГО прогона: видно, кто упал,
кого закрыла стена, у кого обход обрезан потолком. Но если hh начнёт отдавать три
вакансии вместо трёхсот, статус останется `ok` — площадка ответила, парсер отработал,
ошибки нет. С точки зрения прогона всё хорошо; с точки зрения поиска работы
пропало 99% главной площадки.

«Тихо деградировал» — родной брат «тихо потерял», и лечится тем же: сравнением
с собственным прошлым. Счётчики уже пишутся в `run_source` каждый прогон, надо
только их прочитать.

Три вердикта и почему пороги такие:

* **АВАРИЯ** — сейчас ноль, раньше было не ноль. Ноль там, где стабильно были
  сотни, не бывает «вакансий нет»: это сменившаяся вёрстка, протухшая сессия или
  новая стена. Порог здесь не нужен вовсе — ноль после не-нуля всегда авария.
* **ДЕГРАДАЦИЯ** — упало больше чем втрое от медианы.
* **ВСПЛЕСК** — выросло больше чем впятеро. Это тоже сигнал, а не радость:
  обычно так выглядит сломанная дедупликация или обход, поехавший в чужую выдачу.

Медиана, а не среднее: один прогон с падением площадки утащил бы среднее вниз
и спрятал бы следующее падение. Медиана к одиночным выбросам устойчива.

Мелочь не тревожим: у источника, где обычно две-три вакансии, падение «втрое»
— это разница между 3 и 1, то есть шум. Поэтому ниже `MIN_BASE` вердикт даётся
только на аварию (ноль после не-нуля).
"""

from __future__ import annotations

# Сколько прошлых прогонов берём в базу сравнения.
WINDOW = 5
# Медиана ниже этого — источник слишком мелкий, чтобы судить о его «падении втрое».
MIN_BASE = 5
DROP_FACTOR = 3      # во столько раз упало — ДЕГРАДАЦИЯ
SPIKE_FACTOR = 5     # во столько раз выросло — ВСПЛЕСК


def median(values: list[int]) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    mid = len(s) // 2
    return float(s[mid]) if len(s) % 2 else (s[mid - 1] + s[mid]) / 2.0


def history(conn, run_id: int, *, window: int = WINDOW) -> dict[str, list[int]]:
    """{источник: [found прошлых прогонов, свежие первыми]}, БЕЗ текущего.

    Считаются только прогоны, где источник реально отработал (`ok`): прогон,
    в котором площадка была выключена флагом или упала, базой сравнения быть
    не может — иначе «раньше было ноль» и деградация не заметится никогда.
    """
    rows = conn.execute(
        "SELECT source, found FROM run_source "
        "WHERE run_id < ? AND status = 'ok' "
        "ORDER BY run_id DESC", (run_id,)).fetchall()
    out: dict[str, list[int]] = {}
    for r in rows:
        bucket = out.setdefault(r["source"], [])
        if len(bucket) < window:
            bucket.append(int(r["found"] or 0))
    return out


def verdict(found: int, past: list[int],
            offered: int | None = None) -> tuple[str, str] | None:
    """(метка, пояснение) или None, если всё в норме или сравнивать не с чем.

    `offered` — сколько строк отдала САМА площадка, до нашего фильтра профессии.
    Без него ноль читается одинаково в двух совершенно разных случаях, и один из
    них — ложная тревога: 08.08.2026 trudvsem отдал девять вакансий, все до
    одной чужой профессии, а отчёт написал «это не „вакансий нет“, а поломка».
    Площадка была жива и ответила по существу; сломано было только сообщение.
    """
    if not past:
        return None
    base = median(past)
    if base <= 0:
        return None
    seen = f"было {', '.join(str(p) for p in past[:WINDOW])} (медиана {base:.0f})"
    if found == 0:
        if offered:
            # Площадка ответила и отдала строки — просто ни одна не наша.
            # Это не авария и чинится не кодом, а формулировкой запроса.
            return ("ПУСТО ПО ПРОФИЛЮ",
                    f"площадка отдала {offered}, под профиль ноль; {seen}. "
                    f"Площадка жива — смотреть формулировки запроса, не парсер")
        return "АВАРИЯ", f"сейчас 0, {seen} — это не «вакансий нет», а поломка"
    if base >= MIN_BASE and found * DROP_FACTOR < base:
        return "ДЕГРАДАЦИЯ", f"сейчас {found}, {seen} — падение в {base / found:.1f}×"
    if base >= MIN_BASE and found > base * SPIKE_FACTOR:
        return "ВСПЛЕСК", (f"сейчас {found}, {seen} — рост в {found / base:.1f}×; "
                           f"обычно так выглядит сломанный дедуп или чужая выдача")
    return None


def assess(conn, run_id: int, report: list[dict], *,
           window: int = WINDOW) -> list[dict]:
    """Сверяет свежие счётчики с историей. Возвращает только ОТКЛОНЕНИЯ.

    Список пуст — значит все источники в своей норме, и это тоже надо уметь
    сказать одной строкой, а не молчанием.
    """
    past = history(conn, run_id, window=window)
    out: list[dict] = []
    for r in report:
        name = r.get("source")
        if not name or r.get("status") != "ok":
            continue
        # `offered` берём из строки отчёта: сколько площадка ОТДАЛА до
        # нашего фильтра профессии. Без него «ноль» одинаков у мёртвой
        # площадки и у живой, чья выдача целиком чужой профессии.
        v = verdict(int(r.get("found") or 0), past.get(name, []),
                    offered=r.get("offered"))
        if v:
            out.append({"source": name, "label": v[0], "why": v[1],
                        "found": int(r.get("found") or 0)})
    # Сначала аварии: если их несколько, читать надо сверху.
    order = {"АВАРИЯ": 0, "ДЕГРАДАЦИЯ": 1, "ВСПЛЕСК": 2,
             "ПУСТО ПО ПРОФИЛЮ": 3}
    out.sort(key=lambda x: (order.get(x["label"], 9), x["source"]))
    return out


def render(rows: list[dict], *, checked: int = 0) -> str:
    """Блок для покрытия. Норму печатаем тоже — молчание неотличимо от «не считали»."""
    if not rows:
        return (f"\n📈 Здоровье источников: отклонений нет "
                f"(сверено с медианой прошлых прогонов: {checked} источников).")
    out = ["\n📈 ЗДОРОВЬЕ ИСТОЧНИКОВ — сверка с медианой прошлых прогонов:"]
    for r in rows:
        out.append(f"   {r['label']}  {r['source']:<14} {r['why']}")
    out.append("   Это сравнение с ПРОШЛЫМ, а не с ошибкой прогона: статус у таких "
               "источников «ok».")
    return "\n".join(out)
